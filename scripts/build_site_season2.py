def _read_json(path: str, default=None):
    if not os.path.exists(path):
        return default
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def _read_jsonl(path: str) -> List[dict]:
    if os.path.exists(path + ".gz"):
        with gzip.open(path + ".gz", "rt", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]
    return []


class Season2Site:
    """All Season 2 artefacts the pages need, loaded once."""

    def __init__(self, root: str, run_id: str = "") -> None:
        self.root = root
        runs_dir = os.path.join(root, "runs")
        runs = sorted((d for d in os.listdir(runs_dir) if d.startswith("season2-")),
                      ) if os.path.isdir(runs_dir) else []
        if not runs:
            raise SystemExit(f"no season2-* runs under {runs_dir}")
        primary = [r for r in runs if "-primary-" in r] or runs
        self.run_id = run_id or primary[-1]
        self.dir = os.path.join(runs_dir, self.run_id)
        self.manifest = _read_json(os.path.join(self.dir, "manifest.json")) or {}
        self.leaderboard = (_read_json(os.path.join(self.dir, "leaderboard.json"))
                            or {}).get("leaderboard", [])
        self.market = _read_json(os.path.join(self.dir, "market_report.json")) or {}
        self.participants = _read_json(os.path.join(self.dir, "participants.json")) or []
        self.masterfeed = _read_json(os.path.join(self.dir, "masterfeed.json")) or {}
        self.signals = _read_json(os.path.join(self.dir, "signal_book.json")) or {}
        self.verification = _read_json(os.path.join(self.dir, "verification.json")) or {}
        self.market_data = _read_json(os.path.join(self.dir, "market_data.json")) or {}
        self.reports: Dict[str, dict] = {}
        reports_dir = os.path.join(self.dir, "reports")
        if os.path.isdir(reports_dir):
            for name in sorted(os.listdir(reports_dir)):
                if name.endswith(".json"):
                    rep = _read_json(os.path.join(reports_dir, name))
                    if rep and rep.get("username"):
                        self.reports[rep["username"]] = rep
        self.trips = _read_jsonl(os.path.join(self.dir, "ledger_trips.jsonl"))
        self.fills = _read_jsonl(os.path.join(self.dir, "ledger_fills.jsonl"))
        self.curves: Dict[str, List[Tuple[str, float]]] = {}
        for row in _read_jsonl(os.path.join(self.dir, "events", "equity.jsonl")):
            self.curves.setdefault(row["participant"], []).append(
                (row["date"], row["equity"]))
        self.stress: List[dict] = []
        for other in runs:
            if other == self.run_id:
                continue
            self.stress.append({
                "run_id": other,
                "label": (_read_json(os.path.join(runs_dir, other, "manifest.json"))
                          or {}).get("label", other),
                "leaderboard": (_read_json(os.path.join(runs_dir, other,
                                                        "leaderboard.json"))
                                or {}).get("leaderboard", [])})
        self.stress.sort(key=lambda s: s["label"])
        self.collection = _read_json(os.path.join(REPO_ROOT, "data", "real",
                                                  "collection_manifest.json")) or {}
        self.coverage = _read_json(os.path.join(REPO_ROOT, "data", "real",
                                                "coverage_report.json")) or {}
        self.crosscheck = _read_json(os.path.join(REPO_ROOT, "data", "real",
                                                  "crosschecks",
                                                  "price_crosscheck.json")) or {}
        self.provenance = _read_json(os.path.join(self.dir, "data_provenance.json")) or {}
        diagnostics = self.provenance.get("diagnostics") or {}
        self.price_backend = (self.provenance.get("price_source") or
                              diagnostics.get("price_backend") or "yahoo")
        self.price_classes = sorted({str(meta.get("source_class", "UNKNOWN"))
                                     for meta in (diagnostics.get("price_series") or {}).values()})
        self.price_eligibility = price_eligibility.audit_official_prices(
            root=os.path.join(REPO_ROOT, "data", "real"), symbols=realdata.UNIVERSE,
            start=realdata.SEASON2_WARMUP_START, end=realdata.SEASON2_END,
            backend=price_eligibility.OFFICIAL_PRICE_BACKEND)

    # -- lookups -----------------------------------------------------------
    def spec(self, username: str) -> dict:
        return next((p for p in self.participants if p.get("username") == username), {})

    def verification_for(self, username: str) -> dict:
        return next((v for v in self.verification.get("per_participant", [])
                     if v.get("username") == username), {})

    def trips_for(self, username: str) -> List[dict]:
        return [t for t in self.trips if t.get("participant") == username]

    def fills_for(self, username: str) -> List[dict]:
        return [f for f in self.fills if f.get("participant") == username]

    def curve(self, username: str) -> List[Tuple[str, float]]:
        return self.curves.get(username, [])

    def benchmark(self) -> List[Tuple[str, float]]:
        dates = self.market_data.get("dates") or []
        spx = self.market_data.get("spx") or []
        t0 = self.market_data.get("first_competition_index") or 0
        start = (self.manifest.get("competition") or {}).get("starting_cash", 100_000.0)
        if not dates or t0 <= 0 or t0 >= len(spx):
            return []
        base = spx[t0 - 1]
        return [(dates[t], start * spx[t] / base) for t in range(t0, len(spx))]

    def signal_status(self) -> Dict[str, str]:
        return {k: v.get("state") for k, v in (self.masterfeed.get("availability")
                                               or {}).items()}

    def inventory(self) -> dict:
        prov = _read_json(os.path.join(self.dir, "data_provenance.json")) or {}
        return prov.get("inventory") or {}


def _slug(username: str) -> str:
    return username.lstrip("@").replace("/", "_")


def _grid(charts: Sequence[str]) -> str:
    return '<section class="charts">' + "".join(charts) + "</section>"


def _kpis(rows: Sequence[Tuple[str, str, str]]) -> str:
    return '<section class="kpis">' + "".join(
        f'<div class="kpi"><div class="kpi-label">{ESC(k)}</div>'
        f'<div class="kpi-value">{v}</div><div class="kpi-sub">{ESC(s)}</div></div>'
        for k, v, s in rows) + "</section>"


def _link(url: str, text: Optional[str] = None, keep: int = 78) -> str:
    if not url:
        return NA
    shown = text or (url if len(url) <= keep else url[:keep] + "…")
    return f'<a href="{ESC(url)}">{ESC(shown)}</a>'


