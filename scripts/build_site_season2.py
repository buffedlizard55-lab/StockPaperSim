def build_stress(d: Season2Site) -> str:
    labels = ["primary"] + [s["label"] for s in d.stress]
    names = [r["username"] for r in d.leaderboard]
    cells: Dict[str, Dict[str, float]] = {"primary": {
        r["username"]: r["total_return_pct"] for r in d.leaderboard}}
    for s in d.stress:
        cells[s["label"]] = {r["username"]: r["total_return_pct"]
                             for r in s["leaderboard"]}
    rows = [[f"<code>{ESC(n)}</code>"] + [
        signed(cells.get(label, {}).get(n)) for label in labels] for n in names]
    order = [[] for _ in labels]
    for n in names:
        for i, label in enumerate(labels):
            order[i].append((n, cells.get(label, {}).get(n)))
    rank_rows = []
    for i, label in enumerate(labels):
        ranked = sorted([(n, v) for n, v in order[i] if v is not None],
                        key=lambda x: -x[1])
        rank_rows.append([ESC(label)] + [
            f"{j + 1}. {ESC(n)} ({v:+.1f}%)" for j, (n, v) in enumerate(ranked[:5])])
    deltas = []
    for n in names:
        base = cells.get("primary", {}).get(n)
        if base is None:
            continue
        for label in labels[1:]:
            v = cells.get(label, {}).get(n)
            if v is None:
                continue
            deltas.append((abs(v - base), label, n, base, v))
    deltas.sort(reverse=True)
    delta_rows = [[ESC(n), ESC(label), signed(base), signed(v), signed(v - base)]
                  for _, label, n, base, v in deltas[:15]]
    body = f"""
<h1>Stress panel &mdash; the same collected path, a harder venue</h1>
<p class="lede">The collected price path is one realisation: there is no synthetic-seed
panel to average over the way Season 1 has one. What is still a modelling choice is
the venue, so Season 2 re-trades the identical collected bars under two harder
assumptions and publishes every participant's return under all three. A strategy
whose edge survives both is not relying on a cheap spread.</p>
{card("Assumptions", '''
<ul>
<li><strong>primary</strong> &mdash; the venue as declared in <code>sim/config.py</code>:
the tick-constrained spread model, the square-root impact model, a 10% participation
cap of the collected session volume, and a zero-commission retail broker that still pays
exchange and regulatory fees.</li>
<li><strong>stress-costs2x</strong> &mdash; spread coefficient doubled, impact
coefficient doubled, taker fee per share doubled, and a $1.00 commission per order
(the price the referenced paper competitions charge).</li>
<li><strong>stress-thinliquidity</strong> &mdash; displayed depth at the touch halved
and the participation cap cut from 10% to 5% of the collected session volume.</li>
</ul>''', cls="notice")}
{card("Total return under each assumption (%)", table(["participant"] + [
    ESC(l) for l in labels], rows))}
{card("Ranking is not stable under venue assumptions", table(
    ["assumption"] + [f"top {i + 1}" for i in range(5)], rank_rows))}
{card("Largest changes against the primary assumption", table(
    ["participant", "assumption", "primary %", "stressed %", "change"], delta_rows))}
"""
    return page("Stress panel", body, active="season2/stress.html")


