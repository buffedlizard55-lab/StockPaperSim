def _mean(values: Iterable[Optional[float]]) -> Optional[float]:
    vals = [v for v in values if v is not None]
    return round(sum(vals) / len(vals), 5) if vals else None


# --------------------------------------------------------------------------

#: Marker for the Season 2 links injected into Season 1's pages. Its presence is
#: what makes ``inject_banner`` idempotent: a page that already carries the
#: banner is returned unchanged, so the injection can be applied to a whole
#: directory without tracking which files were already done.
BANNER_MARK = 'id="season2-banner"'

BANNER_CALLOUT = (
    '<section id="season2-banner" class="card">'
    '<h2>Season 2 is published with an explicit price-eligibility status</h2>'
    '<p>Season 1 above is a calibrated replay of the real S&amp;P 500 and VIX path. '
    '<strong>Season 2</strong> preserves every collected price file, raw response, '
    'checksum and trade-ledger fact, but a public endpoint is not automatically an '
    'eligible official source. The current Yahoo-backed history is marked '
    '<strong>SECONDARY research</strong>; the official Nasdaq path fails closed until '
    'source, coverage, checksum and redistribution checks pass.</p>'
    '<p><a href="{p}season2/index.html">Season 2 overview</a> · '
    '<a href="{p}season2/leaderboard.html">Leaderboard</a> · '
    '<a href="{p}season2/ledger.html">Verified trade ledger</a> · '
    '<a href="{p}season2/masterfeed.html">MasterFeed register</a> · '
    '<a href="{p}season2/data.html">Data custody</a></p>'
    '</section>')


def inject_banner(html_text: str, callout: bool = True, prefix: str = "") -> str:
    """Add the Season 2 links to a Season 1 page, once.

    Two edits, both idempotent: a nav entry appended to the site's own ``<nav>``
    (every page, so the Season 2 section is reachable from anywhere) and, on the
    overview page only, a callout that says what Season 2 is.  The nav is found by
    its ``</nav>`` close rather than by rewriting the nav list, because Season 1's
    page shell is built by a different script and must stay the single owner of
    its own markup.
    """
    if BANNER_MARK in html_text:
        return html_text
    nav_link = f'<a href="{prefix}season2/index.html">Season 2 (eligibility status)</a>'
    if '</nav>' in html_text:
        html_text = html_text.replace('</nav>', nav_link + '</nav>', 1)
    if callout:
        marker = '<main class="wrap">'
        if marker in html_text:
            html_text = html_text.replace(
                marker, marker + "\n" + BANNER_CALLOUT.format(p=prefix), 1)
        else:  # pragma: no cover - the shell always has a <main>
            html_text = BANNER_CALLOUT.format(p=prefix) + html_text
    return html_text


def _price_status_banner(d: Season2Site) -> str:
    audit = d.price_eligibility
    run_eligible = (audit.get("eligible") and d.price_backend == "nasdaq" and
                    d.price_classes and set(d.price_classes) == {"OFFICIAL"})
    if run_eligible:
        return (
            '<section class="card notice" style="border-color:#1f9d55">'
            '<h2>Official-price eligibility: PASS</h2>'
            '<p>All required symbols passed source-class, raw-response checksum, '
            'retrieval, OHLCV, session-coverage and redistribution checks for the '
            f'{ESC(str(audit.get("backend")))} backend.</p></section>')
    codes = sorted({str(issue.get("code", "invalid")) for issue in audit.get("issues", [])})
    return (
        '<section class="card notice" style="border-color:#c0392b">'
        '<h2>Official-price eligibility: NOT ELIGIBLE</h2>'
        f'<p>This committed run uses <strong>{ESC(d.price_backend)}</strong> price files '
        f'classed <strong>{ESC(", ".join(d.price_classes) or "UNKNOWN")}</strong>. '
        'It is reproducible research, not an official-price competition result. '
        'The strict runner uses the Nasdaq adapter and refuses to trade when official '
        'files, raw checksums, complete dates, OHLCV validation or redistribution '
        'permission are missing.</p>'
        f'<p><strong>Audit flags:</strong> {ESC(", ".join(codes[:12]) or "none")}. '
        'Run <code>python3 -m sim.cli price-audit</code> for the complete report; '
        'no Yahoo/Nasdaq agreement can override this gate.</p></section>')


def build(root: str, out: str, run_id: str = "") -> List[str]:
    global PRICE_STATUS_BANNER
    d = Season2Site(root, run_id)
    PRICE_STATUS_BANNER = _price_status_banner(d)
    written: List[str] = []

    def write(rel: str, content: str) -> None:
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
        written.append(rel)

    write("season2/index.html", build_index(d))
    write("season2/leaderboard.html", build_leaderboard(d))
    write("season2/masterfeed.html", build_masterfeed(d))
    write("season2/ledger.html", build_ledger(d))
    write("season2/stress.html", build_stress(d))
    write("season2/data.html", build_data(d))
    write("season2/participants/index.html", build_participants_index(d))
    for username in sorted(d.reports):
        write(f"season2/participants/{_slug(username)}.html",
              build_participant(d, username))

    payloads = {
        "leaderboard.json": d.leaderboard,
        "participants.json": d.participants,
        "masterfeed.json": d.masterfeed,
        "stress_panel.json": d.stress,
        "ledger_summary.json": {
            "summary": d.verification.get("summary"),
            "digest_sha256": d.verification.get("ledger_digest_sha256"),
            "verification": d.verification.get("per_participant"),
        },
        "crosschecks.json": (d.verification.get("summary") and
                             (d.verification or {}).get("summary")) or {},
        "market_summary.json": d.market,
        "price_eligibility.json": d.price_eligibility,
    }
    for name, payload in payloads.items():
        write(f"assets/data/season2/{name}",
              json.dumps(payload, indent=1, sort_keys=False) + "\n")

    # Prune anything this builder no longer produces. ``docs/`` is committed and
    # diffed against a fresh build in CI, and a JSON payload from an earlier
    # revision of this script (``collected_data.json`` was observed) would keep
    # being served - and keep being diffed - as if it were current. Season 1's
    # builder prunes its participant pages for the same reason.
    keep = set(written)
    for base in ("season2", os.path.join("assets", "data", "season2")):
        directory = os.path.join(out, base)
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            rel = os.path.join(base, name)
            path = os.path.join(directory, name)
            if os.path.isdir(path):
                continue
            if rel not in keep:
                os.remove(path)
    return written


def main(argv: Optional[Sequence[str]] = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--memory-root", default=os.path.join(REPO_ROOT, "memory"))
    parser.add_argument("--out", default=os.path.join(REPO_ROOT, "docs"))
    parser.add_argument("--run", default="")
    args = parser.parse_args(argv)
    written = build(args.memory_root, args.out, args.run)
    print(f"season 2 site: {len(written)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
