def build_masterfeed(d: Season2Site) -> str:
    register = d.masterfeed.get("register") or []
    availability = d.masterfeed.get("availability") or {}
    fire = d.masterfeed.get("fire_counts") or {}
    rows = []
    for row in register:
        signals = row.get("signals") or []
        states = sorted({availability.get(s, {}).get("state", "MISSING")
                         for s in signals}) if signals else []
        if not signals:
            collected = pill("NO-COLLECTED-SIGNAL", "badge-warn")
        elif states == ["AVAILABLE"]:
            collected = pill("AVAILABLE", "badge-ok")
        elif "AVAILABLE" in states:
            collected = pill("PARTIAL", "badge-warn")
        else:
            collected = pill("MISSING", "badge-bad")
        fired = "—"
        if signals:
            counts = [fire.get(s, {}) for s in signals]
            fired = ", ".join(
                f"{s.split('::')[0]}: {c.get('sessions_actionable', '—')}"
                for s, c in zip(signals, counts))
        rows.append([
            ESC(str(row.get("requested_as", ""))),
            _link(str(row.get("site_url", "")), row.get("repo") or "no such project"),
            _link(str(row.get("official_url", ""))),
            pill(str(row.get("source_class", ""))),
            pill(str(row.get("mapping", ""))),
            pill(str(row.get("status", ""))),
            collected,
            f'<code>{ESC(", ".join(signals))}</code>' if signals else NA,
            ESC(str(row.get("mapping_note", ""))),
        ])
    forward = [r for r in register if r.get("status") == "FORWARD-ONLY"]
    body = f"""
<h1>MasterFeed &mdash; what could be verified, and what could not</h1>
<p class="lede">Each row is one item from the brief, traced to the project it names and
to the <strong>official endpoint</strong> a strategy reads. "source class" says who
publishes the data, "mapping" says how strong the link from that project's data to a
tradable instrument honestly is, "status" says whether a backtest was possible at all,
and "collected data" says whether the season actually holds the signal. Nothing is
marked available because it would be convenient.</p>
{table(["requested as", "project", "official source", "source class", "mapping",
        "status", "collected data", "signal arrays", "why this mapping"], rows)}
{card("Forward-only: the strategies that place no backdated trades", f'''
<p>{len(forward)} of {len(register)} items have no retrievable official history:
<ul>{"".join(f"<li><strong>{ESC(str(r.get('requested_as')))}</strong> &mdash; {ESC(str(r.get('mapping_note', '')))}</li>" for r in forward)}</ul></p>
<p>Those strategies exist in the roster, their adapters point at the live official
document, and they report <em>no trades</em> for the season rather than a number built
from data this project could not verify. A scheduled collection run is what turns them
into backtestable participants, and that is the first item in the remaining-work
register.</p>''', cls="notice")}
{card("Signal arrays the season actually holds", table(
    ["signal", "collected state", "sessions actionable", "sessions in window",
     "value on the last session", "official source"],
    [[f"<code>{ESC(k)}</code>", pill(v.get("state", "")),
      str((fire.get(k) or {}).get("sessions_actionable", "—")),
      str((fire.get(k) or {}).get("sessions_in_window", "—")),
      num((fire.get(k) or {}).get("last_value"), F4),
      _link(availability.get(k, {}).get("url", ""))]
     for k, v in sorted(availability.items())]))}
{card("Where the money actually came from", '''
<p>The register answers "could it be measured"; the participant pages answer "did it
make money, and why". Each carries the strategy as declared before the run, its
returns, a post-mortem built from measured quantities only - never from the strategy's
own priors - its round trips with the collected reference prices, and its verification
block.</p>
<p><a href="participants/index.html">All participants &rarr;</a> &middot;
<a href="ledger.html">Trade ledger &rarr;</a></p>''')}
"""
    return page("MasterFeed register", body, active="season2/masterfeed.html")


def build_ledger(d: Season2Site) -> str:
    summary = d.verification.get("summary") or {}
    per_user = []
    for r in d.leaderboard:
        user = r["username"]
        fills = d.fills_for(user)
